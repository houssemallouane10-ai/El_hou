// Writes the list of app files and a content hash into sw.js, so the service
// worker updates (and re-caches everything) whenever any file changes.
// No dependencies: runs before every deploy (see .github/workflows/deploy.yml).
//   node barmaj/tools/stamp.mjs
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const skip = /^(tools\/|sw\.js$|README\.md$)|\.(LICENSE|md|map)$/;

const walk = async (dir) => (await Promise.all((await readdir(dir, { withFileTypes: true })).map((e) => {
  const p = join(dir, e.name);
  return e.isDirectory() ? walk(p) : [p];
}))).flat();

const files = (await walk(app))
  .map((p) => relative(app, p).split('\\').join('/'))
  .filter((p) => !skip.test(p))
  .sort();

const hash = createHash('sha256');
for (const f of files) {
  hash.update(f);
  hash.update(await readFile(join(app, f)));
}
const version = hash.digest('hex').slice(0, 12);
const list = ['./', ...files.filter((f) => f !== 'index.html')];

const swPath = join(app, 'sw.js');
const sw = await readFile(swPath, 'utf8');
const block = `/* precache:start (generated by tools/stamp.mjs) */
const VERSION = '${version}';
const FILES = ${JSON.stringify(list, null, 1).replace(/\n\s*/g, ' ')};
/* precache:end */`;
const next = sw.replace(/\/\* precache:start[\s\S]*?\/\* precache:end \*\//, block);
if (next === sw && !sw.includes(version)) throw new Error('precache markers not found in sw.js');
await writeFile(swPath, next);
console.log(`sw.js stamped: version ${version}, ${list.length} files`);
