export const uiLangs = [
  { id: 'ar', name: 'العربية', dir: 'rtl' },
  { id: 'fr', name: 'Français', dir: 'ltr' },
  { id: 'en', name: 'English', dir: 'ltr' },
];

export const lang = () => (dict[settings.uiLang] ? settings.uiLang : 'ar');

export const t = (key, vars) => {
  const s = dict[lang()][key] ?? dict.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
};

export const hintText = (id, groups) => {
  const s = hints[lang()][id] ?? hints.en[id];
  if (!s) return '';
  const esc = (v) => String(v ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
  return s.replace(/\{(\d)\}/g, (m, i) => esc(groups[i]));
};

// Fill [data-i18n], [data-i18n-title], [data-i18n-placeholder] and set the page direction
export const applyI18n = (root = document) => {
  const l = lang();
  const meta = uiLangs.find((u) => u.id === l);
  document.documentElement.lang = l;
  document.documentElement.dir = meta.dir;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
};
