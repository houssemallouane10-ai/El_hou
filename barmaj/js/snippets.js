// Shortcuts offered while typing: in C, "pri" offers printf("") and puts the
// cursor between the quotes. Tab (on the symbol bar) jumps to the next place.
//
// Each entry is [label, template]. In a template:
//   ${}       a place to type, in order
//   ${name}   a place to type that starts with "name" selected; the same name
//             is edited everywhere at once (the i of a for loop)
//   \n \t     new line and one level of indentation
//   \\{ \\}   a literal { or } where it would read as a place (Ruby "#\\{x\\}")
// Python, JavaScript and TypeScript also get the editor's own blocks
// (def, for, while, if, class…), so they are not repeated here.

const cBlocks = (decl) => [
  ['if', 'if (${}) {\n\t${}\n}'],
  ['else', 'else {\n\t${}\n}'],
  ['else if', 'else if (${}) {\n\t${}\n}'],
  ['for', 'for (' + decl + ' ${i} = 0; ${i} < ${n}; ${i}++) {\n\t${}\n}'],
  ['while', 'while (${}) {\n\t${}\n}'],
  ['do', 'do {\n\t${}\n} while (${});'],
  ['switch', 'switch (${x}) {\n\tcase ${value}:\n\t\t${}\n\t\tbreak;\n\tdefault:\n\t\t${}\n}'],
];

