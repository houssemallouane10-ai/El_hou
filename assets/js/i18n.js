const LOCALES = { ar: 'ar-DZ-u-nu-latn', fr: 'fr-FR', en: 'en-GB' };

function detectLang() {
  const saved = store.get('lang');
  if (UI_LANGS.includes(saved)) return saved;
  const nav = (navigator.language || 'ar').slice(0, 2);
  return UI_LANGS.includes(nav) ? nav : 'ar';
}

let current = detectLang();
const listeners = new Set();

export const getLang = () => current;
export const locale = () => LOCALES[current];

export function t(key, vars = {}) {
  const str = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export function setLang(lang) {
  if (!UI_LANGS.includes(lang)) return;
  current = lang;
  store.set('lang', lang);
  applyDocumentLang();
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) {
  listeners.add(fn);
}

export function applyDocumentLang() {
  const root = document.documentElement;
  root.lang = current;
  root.dir = current === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    const [attr, key] = el.dataset.i18nAttr.split(':');
    el.setAttribute(attr, t(key));
  });
}

// Localized names, used for team-free strings like language labels
export function languageName(code) {
  if (!code || code === 'multi') return t('player.langAll');
  try {
    return new Intl.DisplayNames([LOCALES[current]], { type: 'language' }).of(code) || code;
  } catch {
    return code;
  }
}

export function formatTime(date) {
  return new Intl.DateTimeFormat(LOCALES[current], { hour: '2-digit', minute: '2-digit', hour12: false }).format(date);
}

export function formatDay(date) {
  return new Intl.DateTimeFormat(LOCALES[current], { weekday: 'long', day: 'numeric', month: 'long' }).format(date);
}

export function formatShortDay(date) {
  return new Intl.DateTimeFormat(LOCALES[current], { weekday: 'short', day: 'numeric', month: 'short' }).format(date);
}
